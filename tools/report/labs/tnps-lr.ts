/** Таблиця «елемент 1…8» з рядками показників */
function elementsTable(rows: [string, string[]][]): Block {
  const n = rows[0][1].length
  const cols: Col[] = [{ title: 'Елемент', widthMm: 38 }, ...Array.from({ length: n }, (_, i): Col => ({ title: String(i + 1), widthMm: 17, align: 'center' }))]
  return table(cols, rows.map(([name, cells]) => [name, ...cells]))
}

