import { readFileSync } from 'node:fs'
import { WEIGHTS, URGENCY_HORIZON } from '../../../src/subjects/usr/core/tasks'
import { dash, figure, formula, links, listing, p, section, subsection, type Block } from '../lib/docx'
import { withSite } from '../lib/shots'
import type { LabReport } from '../types'
import { REPO_URL, coreFile, workUrl } from './common'

export const usrTm: LabReport = {
  file: 'УСР_Тренінг',
  async build() {
    const [list, rep] = await withSite('usr/tm', async (_page, shot) => [await shot('.window >> nth=0'), await shot('.window >> nth=1')])
    let f = 0
    const body: Block[] = [
      section('Мета роботи'),
      p('Навчитися моделювати об’єкти та процеси командної роботи, визначати показники пріоритетності задач, оцінювати навантаження членів команди та формувати аналітичні звіти для менеджера; розробити програмний засіб для управління задачами команди.'),

      section('Завдання (варіант 1)'),
      p('Розробити Task Manager для команди з такими можливостями:'),
      dash('створення, редагування та видалення задач;'),
      dash('призначення задач на учасників команди;'),
      dash('встановлення дедлайнів, важливості та складності задач;'),
      dash('автоматичне обчислення пріоритету задач і відображення списку за пріоритетом;'),
      dash('фільтрування задач за статусом (в роботі, завершено, прострочено) і пріоритетом;'),
      dash('формування короткого звіту по задачах команди (топ-3 задачі, прострочені задачі).'),

      section('Хід роботи'),
      subsection('1. Модель даних'),
      p('Задача описується назвою, відповідальним, дедлайном, важливістю (1–5), складністю (1–5) та ознакою завершення. Статус обчислюється автоматично: «Завершено» — якщо задачу позначено виконаною, «Прострочено» — якщо дедлайн минув, інакше — «В роботі».'),
      subsection('2. Формула пріоритету'),
      p('Пріоритет задачі — зважена сума трьох нормованих факторів:'),
      formula(`P = 100 · (${WEIGHTS.importance}·I + ${WEIGHTS.complexity}·S + ${WEIGHTS.urgency}·U),`.replace(/\./g, ',')),
      p(`де I = (важливість − 1)/4 і S = (складність − 1)/4 — важливість і складність, приведені до шкали 0…1; U — терміновість: 1, якщо до дедлайну 0 днів або дедлайн минув, 0 — якщо до дедлайну ${URGENCY_HORIZON} днів і більше, а між цими значеннями змінюється лінійно. Найбільшу вагу має важливість, далі — терміновість, найменшу — складність. Пріоритет від 65 вважається високим, від 40 — середнім, нижче — низьким; завершені задачі мають пріоритет 0 і відображаються в кінці списку.`),
      subsection('3. Звіт для менеджера'),
      p('Звіт містить кількість задач за статусами, частку виконаних задач, три задачі з найвищим пріоритетом, перелік прострочених задач і навантаження кожного учасника (кількість незавершених і прострочених задач, сума балів складності).'),
      subsection('4. Програмна реалізація'),
      p('Програму реалізовано як вебзастосунок мовою TypeScript з бібліотеками React і React-Bootstrap; вона є розділом сайту з навчальними роботами. Логіку винесено в модуль tasks.ts (статус, терміновість, пріоритет, сортування, звіт, перевірка введення), інтерфейс — у TaskManager.tsx. Задачі зберігаються в локальному сховищі браузера, тож дані не губляться після перезавантаження сторінки. Правильність формул перевірено автоматичними тестами.'),
      ...links(workUrl('usr', 'tm'), REPO_URL),
      subsection('5. Результати роботи програми'),
      p(`На рисунку ${f + 1} наведено список задач команди з пріоритетами, статусами та кнопками дій.`),
      ...figure(list, ++f, 'Список задач команди'),
      p(`На рисунку ${f + 1} наведено звіт по задачах команди.`),
      ...figure(rep, ++f, 'Звіт по задачах команди'),

      section('Висновки'),
      p('Розроблено Task Manager для команди, який автоматично обчислює пріоритет задач з урахуванням важливості, складності й терміновості, відображає задачі за пріоритетом, фільтрує їх за статусом і пріоритетом та формує звіт для менеджера. Така модель дозволяє швидко побачити найважливіші та прострочені задачі й нерівномірність навантаження в команді.'),

      section('Додаток А. Лістинг обчислювальної частини', true),
      ...listing('tasks.ts', readFileSync(coreFile('usr', 'tasks.ts'), 'utf8')),
    ]
    return {
      title: {
        workNo: 0,
        discipline: 'Управління та стратегічний розвиток ІТ-бізнесу',
        topic: 'Розробка ПЗ для управління командою. Варіант 1: Task Manager для команди',
        kind: 'про виконання тренінгу та самостійної роботи',
        teacher: { position: '', name: '', female: false },
      },
      body,
      docTitle: 'Тренінг та самостійна робота — УСР',
    }
  },
}
